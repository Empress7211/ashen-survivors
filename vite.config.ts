import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { defineConfig, type Plugin } from 'vite';

function isCoreShellAsset(relPath: string): boolean {
  if (relPath === 'index.html' || relPath === 'manifest.webmanifest') {
    return true;
  }
  if (/^assets\/[^/]+\.(?:js|css)$/.test(relPath)) {
    return true;
  }
  if (/^assets\/fonts\/[^/]+\.woff2$/.test(relPath)) {
    return true;
  }
  if (/^assets\/atlases\/[^/]+$/.test(relPath)) {
    return true;
  }
  return false;
}

function walkFiles(dir: string, rootDir: string, out: string[]): void {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const absPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walkFiles(absPath, rootDir, out);
    } else if (entry.isFile()) {
      const rel = path.relative(rootDir, absPath).split(path.sep).join('/');
      if (isCoreShellAsset(rel)) {
        out.push(rel);
      }
    }
  }
}

function buildServiceWorkerSource(cacheName: string, precacheUrls: readonly string[]): string {
  return `/* Auto-generated by ashenPwaPlugin() during vite build */
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) =>
        Promise.all(
          PRECACHE_URLS.map((url) =>
            cache.add(new Request(url, { cache: 'reload' })).catch(() => undefined),
          ),
        ),
      )
      .catch(() => undefined)
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith('ashen-cache-') && key !== CACHE_NAME)
            .map((key) => caches.delete(key)),
        ),
      )
      .catch(() => undefined)
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  let url;
  try {
    url = new URL(request.url);
  } catch {
    return;
  }

  if (url.protocol !== 'http:' && url.protocol !== 'https:') return;
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate' || url.pathname === '/' || url.pathname === '/index.html') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response && response.ok) {
            const copy = response.clone();
            caches
              .open(CACHE_NAME)
              .then((cache) => cache.put('/index.html', copy))
              .catch(() => undefined);
          }
          return response;
        })
        .catch(() =>
          caches
            .open(CACHE_NAME)
            .then((cache) =>
              cache
                .match('/index.html', { ignoreVary: true })
                .then((cached) => cached || cache.match(request, { ignoreVary: true })),
            )
            .then((cached) => cached || new Response('Offline', { status: 503, statusText: 'Offline' }))
            .catch(() => new Response('Offline', { status: 503, statusText: 'Offline' })),
        ),
    );
    return;
  }

  if (url.pathname.startsWith('/assets/') || url.pathname === '/manifest.webmanifest') {
    event.respondWith(
      caches
        .open(CACHE_NAME)
        .then((cache) =>
          cache.match(request, { ignoreVary: true }).then((cached) => {
            if (cached) return cached;
            return fetch(request)
              .then((response) => {
                if (response && response.ok) {
                  cache.put(request, response.clone()).catch(() => undefined);
                }
                return response;
              })
              .catch(() => new Response('', { status: 504, statusText: 'Offline' }));
          }),
        )
        .catch(() => new Response('', { status: 504, statusText: 'Offline' })),
    );
  }
});
`;
}

function ashenPwaPlugin(): Plugin {
  let outDir = path.resolve(process.cwd(), 'dist');

  return {
    name: 'ashen-pwa',
    apply: 'build',
    configResolved(config) {
      outDir = path.resolve(config.root, config.build.outDir);
    },
    closeBundle() {
      if (!fs.existsSync(outDir)) return;

      const coreFiles: string[] = [];
      walkFiles(outDir, outDir, coreFiles);
      coreFiles.sort();

      const hash = crypto.createHash('sha256');
      for (const relPath of coreFiles) {
        const absPath = path.join(outDir, relPath);
        if (!fs.existsSync(absPath)) continue;
        hash.update(relPath);
        hash.update('\0');
        hash.update(fs.readFileSync(absPath));
      }

      const shortHash = hash.digest('hex').slice(0, 12);
      const cacheName = `ashen-cache-${shortHash}`;
      const precacheUrls = coreFiles.map((rel) => `/${rel}`);
      const swSource = buildServiceWorkerSource(cacheName, precacheUrls);

      fs.writeFileSync(path.join(outDir, 'sw.js'), swSource, 'utf8');
    },
  };
}

export default defineConfig({
  plugins: [ashenPwaPlugin()],
  build: {
    rollupOptions: {
      output: {
        manualChunks: {
          phaser: ['phaser'],
        },
      },
    },
  },
});
