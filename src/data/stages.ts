import type { EnemyId, StageId } from '../contracts/ids.ts';
import type { StageDef, WaveEntry } from '../contracts/types.ts';

interface WaveTemplate {
  startMinute: number;
  endMinute: number;
  enemies: readonly EnemyId[];
  baseInterval: number;
  baseMinCount: number;
  minCountStep: number;
  baseHpMult: number;
  hpStep: number;
  speedMult?: number;
  damageMult?: number;
}

function expandWaves(templates: readonly WaveTemplate[]): WaveEntry[] {
  const result: WaveEntry[] = [];
  for (const tpl of templates) {
    for (let m = tpl.startMinute; m <= tpl.endMinute; m++) {
      const offset = m - tpl.startMinute;
      const interval = Math.max(0.18, Number((tpl.baseInterval - offset * 0.03).toFixed(2)));
      const minCount = tpl.baseMinCount + offset * tpl.minCountStep;
      result.push({
        minute: m,
        endMinute: m + 1,
        enemies: tpl.enemies,
        spawnInterval: interval,
        minimumCount: minCount,
        maxCount: Math.max(minCount + 40, Math.round(minCount * 1.85)),
        hpMultiplier: Number((tpl.baseHpMult + offset * tpl.hpStep).toFixed(2)),
        speedMultiplier: tpl.speedMult ?? 1.0,
        damageMultiplier: tpl.damageMult ?? 1.0,
      });
    }
  }
  return result;
}

